#!/usr/bin/env node
//
// Fail when a documented command would not run.
//
// The class of defect: a bash block tells a reader (or an agent following a skill) to run
// `playwright-cli open`, but that binary lives in `node_modules/.bin/` and is not on PATH, so
// the line fails with `command not found`. Nobody notices, because documentation is not
// executed — the same way `/scaffold-page-object`'s component table drifted for three months
// (ADR-0025). Prose asserting "always use npx" is worth exactly as much as the check behind it.
//
// So: scan every bash block in the markdown this repository owns, and flag any line invoking a
// binary that exists ONLY in node_modules/.bin. The fix is always to prefix it with `npx`.
//
// The vendored `@playwright/cli` skill is excluded. It is regenerated by
// `npx playwright-cli install --skills`, so a correction made there is undone by the next
// upgrade; CLAUDE.md carries the standing correction where regeneration cannot reach it.

import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

// Two exclusions, for opposite reasons.
//
// The vendored `@playwright/cli` skill is regenerated by `npx playwright-cli install --skills`,
// so a correction made there is undone by the next upgrade; CLAUDE.md carries the standing
// correction where regeneration cannot reach it.
//
// The dated design plans are the Log layer, not the Present one (see `docs/architecture.md`).
// They record what was planned on a given day. Rewriting a May plan so it passes a check written
// in September falsifies the record for the same reason we supersede an ADR rather than edit it,
// and nobody executes a design plan anyway.
const EXCLUDED = ['.claude/skills/playwright-cli/', 'docs/superpowers/plans/'];
const SKIP_DIRS = new Set(['node_modules', '.git', 'test-results', 'playwright-report']);

const localBins = new Set(readdirSync('node_modules/.bin'));

function* markdownFiles(dir) {
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry)) continue;
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) yield* markdownFiles(path);
    else if (entry.endsWith('.md')) yield path;
  }
}

const findings = [];

for (const file of markdownFiles('.')) {
  const relative = file.replace(/^\.\//, '');
  if (EXCLUDED.some((prefix) => relative.startsWith(prefix))) continue;

  let inBash = false;
  readFileSync(file, 'utf-8')
    .split('\n')
    .forEach((line, i) => {
      if (/^\s*```\s*(bash|sh|shell)\b/.test(line)) return void (inBash = true);
      if (/^\s*```/.test(line)) return void (inBash = false);
      if (!inBash) return;

      // Only a line that STARTS with the binary is an invocation. `npx playwright-cli`,
      // `# playwright-cli …` and prose mid-line are all fine.
      const match = /^\s*([a-z0-9@/._-]+)\s/i.exec(line);
      if (match && localBins.has(match[1])) {
        findings.push({ file, line: i + 1, binary: match[1], text: line.trim() });
      }
    });
}

if (findings.length > 0) {
  console.error(
    `check-doc-commands: ${findings.length} documented command(s) would fail with ` +
      '"command not found" — the binary is in node_modules/.bin, not on PATH.\n' +
      'Prefix each with `npx`.\n',
  );
  for (const f of findings) console.error(`  ${f.file}:${f.line}  ${f.text}`);
  process.exit(1);
}

console.log(
  `check-doc-commands: no documented command shadows a node_modules/.bin binary ` +
    `(${localBins.size} local binaries checked).`,
);
